function done = LLMPatch_Transition(transition, rt, transitionIndex, logger)
    done = false;
    originalLabel = strtrim(transition.LabelString);

    if isInitialTransition(transition)
        fprintf('\nTransition. %d: [Initial transition] — skipping.\n', transitionIndex);
        logger.log(transitionIndex, originalLabel, false, false, "[Skipped: Initial Transition]");
        return;
    end

    data_faulty = rt.find('-isa', 'Stateflow.Data');
    inputs_faulty = data_faulty(strcmp({data_faulty.Scope}, 'Input'));
    outputs_faulty = data_faulty(strcmp({data_faulty.Scope}, 'Output'));
    locals_faulty = data_faulty(strcmp({data_faulty.Scope}, 'Local'));
    parameters_faulty = data_faulty(strcmp({data_faulty.Scope}, 'Parameter'));

    inputNames = unique([string({inputs_faulty.Name})]);
    outputNames = unique(string({outputs_faulty.Name}));
    localNames = unique([string({locals_faulty.Name})]);
    paramNames = unique([string({parameters_faulty.Name})]);

    variableContext = sprintf([ ...
        'Available variables:\n' ...
        '- Inputs: %s\n' ...
        '- Outputs: %s\n' ... 
        '- Locals: %s\n' ...
        '- Parameters: %s\n\n'], ...
        strjoin(inputNames, ', '), strjoin(outputNames, ', '), strjoin(localNames, ', '), strjoin(paramNames, ', '));

    try
        fewshotExamples = fileread("fewshot_transitions.json");
    catch
        warning('fewshot_transitions.json not found. Continuing without examples.');
        fewshotExamples = '';
    end

    promptTemplate = strjoin({
        'You are a Stateflow Repair Assistant. Your task is to examine the condition labels of transitions in a Stateflow model.',...
        ' Always provide a possible mutation because the transition is highly likely to be buggy.'... 
        '--- Context ---\n', ...
        'Transition ID: "%s"\n', ...
        'condition label:\n"%s"\n\n', ...
        'Variable context (use ONLY these variables, do not invent new ones):\n%s\n\n', ...
        '--- Repair Instructions ---\n', ...
        '1. Examples of mutations are below, but not limited to these:\n', ...
        '   - Replace relational, conditional, or math operators.\n', ...
        '   - Change numeric values.\n', ...
        '   - Remove duplications in expressions\n',...
        '   - Insert or delete simple conditions if the transition has multiple conditions.\n', ...
        '   - Replace wrong boolean values (true <-> false).\n', ...
        '   - Replace wrong logical operators (&& <-> ||).\n', ...
        '   - Replace wrong time delays (e.g., after(5,sec) <-> after(10,sec)).\n', ...
        '   - Simplify or expand compound conditions (e.g., [TEMP > REF + 2 || TEMP < REF + 2] <-> [TEMPERATURE > REF + 2]).\n', ...
        '3. Restrictions:\n', ...
        'Provide only a single line output ',...
        '   - Do NOT invent variables.\n', ...
        '   - Do NOT change source or destination states.\n', ...
        '   - Do NOT delete the transition.\n', ...
        '   - Do NOT add complex nested conditions.\n', ...
        '4. Ensure the result is compilable in MATLAB Stateflow.\n\n', ...
        '--- Output Format ---\n', ...
        'STRICT JSON ONLY. No explanations, no extra text.\n', ...
        'Format:\n', ...
        '{ "patch": "<patched label here>" }\n\n', ...
        '--- Few-Shot Examples ---\n', ...
        'here are some few-Shot Examples (for guidance only, do not copy) \n',...
        '%s\n'
    }, '');
   

        prompt = sprintf(promptTemplate, char(transition.Id), originalLabel, variableContext, fewshotExamples);


    % prompt = sprintf("%s\n%s", variableContext, ...
    % %     sprintf(promptTemplate,functionalContext, char(transition.Id), originalLabel, variableContext, fewshotExamples));
    % promptBody = sprintf(promptTemplate, char(transition.Id), originalLabel, variableContext,fewshotExamples);   
    % prompt = sprintf("\n%s", promptBody);
    

    try
        fprintf('\nTransition. %d: "%s"\n', transitionIndex, originalLabel);
        gptResponse = callChatGPT(prompt);

        match = regexp(gptResponse, '"patch"\s*:\s*"([^"]+)"', 'tokens', 'once');
        if ~isempty(match)
            newLabel = strtrim(match{1});

            if isempty(newLabel) || contains(lower(newLabel), 'non-compilable') || ...
               length(newLabel) > 300 || ...
               count(newLabel, '[') ~= count(newLabel, ']')
                fprintf('LLM detected a Fault\n');
                fprintf('LLM could not provide a valid patch\n');
                logger.log(transitionIndex, originalLabel, true, false, "");
                return;
            end

            if ~strcmp(originalLabel, newLabel)
                fprintf('LLM detected a Fault\n');
                fprintf('LLM provided a valid patch: "%s"\n', newLabel);
                transition.LabelString = newLabel;
                done = true;
                logger.log(transitionIndex, originalLabel, true, true, newLabel);
            else
                fprintf('LLM did not detect a Fault\n');
                fprintf('LLM could not provide a valid patch\n');
                logger.log(transitionIndex, originalLabel, false, false, "");
            end
        else
            fprintf('LLM did not detect a Fault\n');
           % fprintf('LLM could not provide a valid patch\n');
            logger.log(transitionIndex, originalLabel, false, false, "");
        end

    catch ME
        disp('GPT mutation failed:');
        %disp(getReport(ME));
        logger.log(transitionIndex, originalLabel, false, false, "");
    end
end

function result = isInitialTransition(transition)
    result = isempty(transition.Source);
end

